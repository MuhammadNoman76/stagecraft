using System.Collections.Concurrent;
using System.Windows.Media;

namespace Stagecraft.Core.Rendering;

/// <summary>An icon from the catalogue (Fluent UI System Icons, 24 x 24).</summary>
public sealed class IconInfo
{
    internal IconInfo(string key, string keywords, string data)
    {
        Key = key;
        Keywords = keywords;
        Data = data;
        Name = string.Join(" ", key.Split('_').Select(w => w.Length == 0 ? w : char.ToUpperInvariant(w[0]) + w.Substring(1)));
        SearchText = (key.Replace('_', ' ') + " " + keywords).ToLowerInvariant();
    }

    public string Key { get; }
    public string Name { get; }
    public string Keywords { get; }
    public string Data { get; }
    public string SearchText { get; }
}

/// <summary>The icons that can be placed on slides (generated by tools\make-icons.mjs, embedded in this assembly).</summary>
public static class IconCatalog
{
    private static readonly Lazy<IReadOnlyList<IconInfo>> s_all = new(Load);
    private static readonly ConcurrentDictionary<string, Geometry?> s_geometry = new(StringComparer.OrdinalIgnoreCase);
    private static Dictionary<string, IconInfo>? s_byKey;

    /// <summary>The icon size the path data is drawn for.</summary>
    public const double Size = 24;

    /// <summary>Shown first when nothing is searched.</summary>
    public static IReadOnlyList<string> Popular { get; } = new[]
    {
        "rocket", "lightbulb", "target", "people_team", "people", "person", "chat", "mail", "globe", "earth", "building",
        "briefcase", "money", "savings", "wallet", "data_trending", "data_pie", "data_bar_vertical", "arrow_trending", "trophy",
        "ribbon", "star", "heart", "shield", "lock_closed", "key", "flash", "sparkle", "checkmark_circle", "calendar", "clock",
        "timer", "flag", "map", "location", "airplane", "vehicle_car", "home", "cart", "gift", "drink_coffee", "food", "leaf_two",
        "weather_sunny", "cloud", "database", "code", "laptop", "phone", "desktop", "camera", "video", "mic", "book", "hat_graduation",
        "brain", "puzzle_piece", "handshake", "megaphone", "document", "folder", "box", "cube", "settings", "wrench", "toolbox",
        "speedometer", "gauge", "scales", "organization", "flowchart", "diagram", "timeline", "compass_northwest", "eye", "search",
    };

    public static IReadOnlyList<IconInfo> All => s_all.Value;

    public static IconInfo? Find(string? key)
    {
        if (string.IsNullOrEmpty(key)) return null;
        s_byKey ??= All.GroupBy(i => i.Key, StringComparer.OrdinalIgnoreCase).ToDictionary(g => g.Key, g => g.First(), StringComparer.OrdinalIgnoreCase);
        return s_byKey.TryGetValue(key!, out var info) ? info : null;
    }

    /// <summary>The frozen geometry (24 x 24) of an icon, or null if the key is unknown.</summary>
    public static Geometry? Geometry(string? key)
    {
        if (string.IsNullOrEmpty(key)) return null;
        return s_geometry.GetOrAdd(key!, k =>
        {
            var info = Find(k);
            if (info == null) return null;
            try
            {
                var g = System.Windows.Media.Geometry.Parse(info.Data);
                g.Freeze();
                return g;
            }
            catch
            {
                return null;
            }
        });
    }

    /// <summary>Icons whose name or keywords contain every word of <paramref name="query"/>, best matches first.</summary>
    public static IReadOnlyList<IconInfo> Search(string? query)
    {
        var words = (query ?? "").ToLowerInvariant().Split(new[] { ' ', ',', '-' }, StringSplitOptions.RemoveEmptyEntries);
        if (words.Length == 0)
        {
            // Favourites for presentations first, then everything else.
            var popular = Popular.Select(Find).Where(i => i != null).Cast<IconInfo>().ToList();
            var keys = new HashSet<string>(popular.Select(p => p.Key));
            return popular.Concat(All.Where(i => !keys.Contains(i.Key))).ToList();
        }
        return All
            .Select(i => (Icon: i, Score: Score(i, words)))
            .Where(x => x.Score > 0)
            .OrderByDescending(x => x.Score)
            .ThenBy(x => x.Icon.Key, StringComparer.Ordinal)
            .Select(x => x.Icon)
            .ToList();
    }

    private static int Score(IconInfo icon, string[] words)
    {
        var score = 0;
        var keyWords = icon.Key.Split('_');
        foreach (var w in words)
        {
            if (keyWords.Any(k => k == w)) score += 10;
            else if (keyWords.Any(k => k.StartsWith(w, StringComparison.Ordinal))) score += 6;
            else if (icon.SearchText.Contains(w)) score += 3;
            else return 0;
        }
        if (icon.Key == string.Join("_", words)) score += 20;
        return score - keyWords.Length; // simpler icons first
    }

    private static IReadOnlyList<IconInfo> Load()
    {
        var list = new List<IconInfo>();
        try
        {
            using var stream = typeof(IconCatalog).Assembly.GetManifestResourceStream("Stagecraft.IconCatalog.txt");
            if (stream == null) return list;
            using var reader = new StreamReader(stream);
            string? line;
            while ((line = reader.ReadLine()) != null)
            {
                if (line.Length == 0 || line[0] == '#') continue;
                var parts = line.Split('\t');
                if (parts.Length < 3) continue;
                list.Add(new IconInfo(parts[0], parts[1], parts[2]));
            }
        }
        catch
        {
            // An empty catalogue just means no icons to pick.
        }
        return list;
    }
}
